/**
 * Generates a Dockerfile and fly.toml for a detected app type.
 *
 * Writes both files into `dir` (the extracted user code directory).
 * Any existing Dockerfile is left untouched (kind === "dockerfile").
 */

import fs from "fs/promises";
import path from "path";
import type { AppType } from "./appDetector";

// App container default port; proxy sidecar always listens on 8787.
const APP_PORT = 8080;
const PROXY_PORT = 8787;

// ─── fly.toml v2 ─────────────────────────────────────────────────────────────

function flyToml(appName: string, appId: string, appPort: number): string {
  const proxyImage = process.env.PROXY_IMAGE!;
  const apiUrl = process.env.API_PUBLIC_URL!;
  const loginUrl = (process.env.WEB_URL ?? "") + "/access";

  const machineConfigObj = {
    containers: [
      {
        name: "proxy",
        image: proxyImage,
        env: {
          SSC_APP_ID: appId,
          SSC_API_URL: apiUrl,
          SSC_LOGIN_URL: loginUrl,
          LISTEN_PORT: String(PROXY_PORT),
          APP_PORT: String(appPort),
        },
        secrets: [{ env_var: "SSC_PROXY_TOKEN", name: "SSC_PROXY_TOKEN" }],
        healthchecks: [
          {
            name: "listening",
            tcp: { port: PROXY_PORT },
            interval: 1,
            timeout: 1,
            grace_period: 0,
            success_threshold: 1,
            failure_threshold: 3,
          },
        ],
      },
      {
        name: "app",
        image: "placeholder",
        env: { PORT: String(appPort) },
        depends_on: [{ name: "proxy", condition: "healthy" }],
      },
    ],
  };

  const machineConfigJson = JSON.stringify(machineConfigObj);
  if (machineConfigJson.includes("'''")) {
    throw new Error("machine_config JSON contains TOML literal-string delimiters (''') — cannot serialize");
  }

  return `# Auto-generated by Small Software Cloud
app = "${appName}"
primary_region = "ord"

[experimental]
  container = "app"
  machine_config = '''${machineConfigJson}'''

[http_service]
  internal_port = ${PROXY_PORT}
  force_https = true
  auto_stop_machines = "suspend"
  auto_start_machines = true
  min_machines_running = 1

[[vm]]
  memory = "256mb"
  cpu_kind = "shared"
  cpus = 1
`;
}

// ─── Node.js ──────────────────────────────────────────────────────────────────

function nodeDockerfile(pm: "npm" | "pnpm" | "yarn", startCmd: string): string {
  const installCmd =
    pm === "pnpm"
      ? "RUN npm install -g pnpm && pnpm install --frozen-lockfile"
      : pm === "yarn"
      ? "RUN yarn install --frozen-lockfile"
      // npm ci requires a lockfile; use it when one was committed, otherwise
      // fall back to npm install. The lockfile presence determines pm="npm"
      // detection, so check at build time by testing for package-lock.json.
      : "RUN if [ -f package-lock.json ]; then npm ci --omit=dev; else npm install --omit=dev; fi";

  return `FROM node:20-alpine
WORKDIR /app

COPY package*.json ${pm === "pnpm" ? "pnpm-lock.yaml* " : pm === "yarn" ? "yarn.lock* " : ""}./
${installCmd}

COPY . .

ENV PORT=${APP_PORT}
ENV NODE_ENV=production
EXPOSE ${APP_PORT}

CMD ${JSON.stringify(["sh", "-c", startCmd])}
`;
}

// ─── Python ──────────────────────────────────────────────────────────────────

function pythonDockerfile(
  server: "gunicorn" | "uvicorn",
  entrypoint: string
): string {
  const serverPkg = server === "uvicorn" ? "uvicorn[standard]" : "gunicorn";
  const cmd =
    server === "uvicorn"
      ? `uvicorn ${entrypoint} --host 0.0.0.0 --port ${APP_PORT}`
      : `gunicorn ${entrypoint} --bind 0.0.0.0:${APP_PORT} --workers 2`;

  return `FROM python:3.11-slim
WORKDIR /app

COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt ${serverPkg}

COPY . .

ENV PORT=${APP_PORT}
EXPOSE ${APP_PORT}

CMD ["sh", "-c", "${cmd}"]
`;
}

// ─── Static (nginx) ───────────────────────────────────────────────────────────

const NGINX_CONF_FILE = "ssc-nginx.conf";

function nginxConfig(): string {
  return `server {
    listen ${APP_PORT};
    server_name _;
    root /usr/share/nginx/html;
    index index.html;
    server_tokens off;
    location ~ /\\. {
        return 404;
    }
    location / {
        try_files $uri $uri/ =404;
    }
}
`;
}

function staticDockerfile(): string {
  return `FROM nginx:alpine
COPY ${NGINX_CONF_FILE} /etc/nginx/conf.d/default.conf
COPY . /usr/share/nginx/html
RUN rm -f /usr/share/nginx/html/${NGINX_CONF_FILE}
EXPOSE ${APP_PORT}
`;
}

// .dockerignore contents — static excludes dotfiles and generated deploy files;
// node/python exclude only .git.
// Dockerfile and fly.toml are excluded from static images so they are not
// reachable from the document root (Docker still builds with them present —
// .dockerignore only controls what is SENT INTO the build context, not what
// is already in the directory when docker build runs).
const STATIC_DOCKERIGNORE = `.git\n.*\n**/.*\n*.pem\n*.key\nid_rsa*\nDockerfile\nfly.toml\n`;
const NODE_PYTHON_DOCKERIGNORE = `.git\n`;

// ─── Public API ───────────────────────────────────────────────────────────────

/**
 * Reads the first EXPOSE directive from the Dockerfile in `dir`.
 * Supports `EXPOSE 3000` and `EXPOSE 3000/tcp`.
 * Returns undefined if no Dockerfile exists or no EXPOSE is found.
 */
export async function sniffExposePort(dir: string): Promise<number | undefined> {
  try {
    const raw = await fs.readFile(path.join(dir, "Dockerfile"), "utf8");
    const m = raw.match(/^EXPOSE\s+(\d+)(?:\/\w+)?/im);
    if (m) return parseInt(m[1], 10);
  } catch {
    // No Dockerfile or unreadable — return undefined
  }
  return undefined;
}

/**
 * Generates Dockerfile and fly.toml for the given app type.
 *
 * appPort — the port the app container listens on.
 *   • Generated apps (node, python, static): always APP_PORT (8080); caller may omit.
 *   • User-supplied Dockerfile: sniffs EXPOSE from the Dockerfile when appPort is
 *     not provided.  Passing 8787 is an error that must be caught before any Fly
 *     API calls are made (deployRunner enforces this via sniffExposePort).
 */
export async function generateDeployFiles(
  dir: string,
  appName: string,
  appType: AppType,
  appId?: string,
  appPort?: number,
): Promise<{ internalPort: number }> {
  let dockerfile: string;

  switch (appType.kind) {
    case "dockerfile": {
      // User-supplied Dockerfile: don't overwrite it, just write fly.toml.
      // Sniff the EXPOSE port when the caller hasn't provided one explicitly.
      const effectiveAppPort = appPort ?? (await sniffExposePort(dir)) ?? APP_PORT;
      await fs.writeFile(path.join(dir, "fly.toml"), flyToml(appName, appId ?? "", effectiveAppPort));
      return { internalPort: effectiveAppPort };
    }

    case "node":
      dockerfile = nodeDockerfile(appType.packageManager, appType.startCommand);
      await fs.writeFile(path.join(dir, ".dockerignore"), NODE_PYTHON_DOCKERIGNORE);
      break;

    case "python":
      dockerfile = pythonDockerfile(appType.server, appType.entrypoint);
      await fs.writeFile(path.join(dir, ".dockerignore"), NODE_PYTHON_DOCKERIGNORE);
      break;

    case "static":
      dockerfile = staticDockerfile();
      await fs.writeFile(path.join(dir, NGINX_CONF_FILE), nginxConfig());
      await fs.writeFile(path.join(dir, ".dockerignore"), STATIC_DOCKERIGNORE);
      break;
  }

  await fs.writeFile(path.join(dir, "Dockerfile"), dockerfile);
  await fs.writeFile(path.join(dir, "fly.toml"), flyToml(appName, appId ?? "", APP_PORT));

  return { internalPort: APP_PORT };
}
